static const uint32_t ESR_EL1_EC_SHIFT = 26;
static const uint32_t ESR_EL1_EC_BITS = 0b111111;

static const uint64_t EC_UDF_INS = 0;

// Data Abort exception taken without a change in Exception level.
// Used for MMU and MPU faults generated by instruction accesses and synchronous
// External aborts, including synchronous parity or ECC errors. Not used for
// debug-related exceptions
static const uint64_t EC_DATA_ABRT = 37; // 0b100101;

extern "C" bool Exception::exception_handler(ExceptionFrame* frame_ptr) {
  uint64_t exception_syndrome = 0;
  asm ("mrs %0, ESR_EL1" : "=r" (exception_syndrome));

  uint64_t exception_link = 0;
  asm ("mrs %0, ELR_EL1" : "=r" (exception_link));

  // The exception class holds what kind of exception has occurred
  const uint64_t exception_class = (exception_syndrome >> ESR_EL1_EC_SHIFT) & ESR_EL1_EC_BITS;

  const bool bad_ec = exception_class == EC_UDF_INS ||
                      exception_class == EC_DATA_ABRT;

  kprintf("\nGot an exception (from %p)\n", exception_link);
  kprintf("- The EC is: %d\n", exception_class);

  frame_ptr->print_frame();

  return bad_ec;
}

extern "C" uint32_t Exception::irq_handler(uint32_t intid, ExceptionFrame* frame_ptr) {
  (void)frame_ptr;
  //kprintf("IRQ INTID %d handled by %d\n", intid, CPU::id());

  kprecond(GIC::driver()->version() == GIC::DriverVersion::v2 || (intid != 1022 && intid != 1023));

  if (intid == 30) {
    kprintf("[%z] Generic Timer Interrupt (INTID %d)\n", CPU::id(), intid);
    Timer::set_timer();
  } else if (intid == UART::intid()) {
    // The UART hardware has sent an interrupt signaling that there is input available to read from ...
    // The UART hardware has sent an interrupt signaling that there is room available to send character to ...
    UART::pl011_handle_irq();
  } else {
    kprintf("[%z] Unhandled interrupt with INTID: %d\n", CPU::id(), intid);
  }

  return intid;
}
