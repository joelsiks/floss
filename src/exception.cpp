uint64_t Exception::exception_level() {
  uint64_t el;
  asm("mrs %0, CurrentEL" : "=r" (el));
  el = el >> 2 & 0b11;

  return el;
}

void Exception::mask_irqs() {
  asm volatile("msr DAIFSet, #0b0010" ::: "memory");
}

void Exception::unmask_irqs() {
  asm volatile("msr DAIFClr, #0b0010" ::: "memory");
}

